$ErrorActionPreference = 'Stop'

# Find the project root based on this script's location.
$projectRoot = Split-Path -Parent $PSScriptRoot

$outputPath = Join-Path $projectRoot 'docs/project-structure.md'

# Folders we want documented.
$rootFolders = @(
    'app'
    'components'
    'features'
    'lib'
    'prisma'
    'public'
    'scripts'
)

# Important files at the project root.
$rootFiles = @(
    '.dockerignore'
    '.env.example'
    '.env.production.example'
    'Dockerfile'
    'compose.yaml'
    'next.config.ts'
    'package.json'
    'prisma7.config.ts'
    'proxy.ts'
    'tsconfig.json'
    'vitest.config.mts'
)

# Never include generated/build/dependency folders.
$excludedNames = @(
    '.git'
    '.next'
    'node_modules'
    'coverage'
    'generated'
    'dist'
    'build'
)

function Get-MarkdownChildren {
    param(
        [string]$Path,
        [int]$Depth
    )

    $result = New-Object System.Collections.Generic.List[string]

    $items = @(
        Get-ChildItem -LiteralPath $Path -Force |
            Where-Object {
                $excludedNames -notcontains $_.Name
            } |
            Sort-Object `
                @{ Expression = { if ($_.PSIsContainer) { 0 } else { 1 } } },
                Name
    )

    foreach ($item in $items) {
        $indent = '  ' * $Depth

        if ($item.PSIsContainer) {
            $displayName = "$($item.Name)/"
        }
        else {
            $displayName = $item.Name
        }

        $result.Add("$indent- $displayName")

        if ($item.PSIsContainer) {
            $children = Get-MarkdownChildren `
                -Path $item.FullName `
                -Depth ($Depth + 1)

            foreach ($child in $children) {
                $result.Add($child)
            }
        }
    }

    return $result
}

$treeLines = New-Object System.Collections.Generic.List[string]

foreach ($folder in $rootFolders) {
    $folderPath = Join-Path $projectRoot $folder

    if (Test-Path -LiteralPath $folderPath) {
        $treeLines.Add("- $folder/")

        $children = Get-MarkdownChildren `
            -Path $folderPath `
            -Depth 1

        foreach ($child in $children) {
            $treeLines.Add($child)
        }
    }
}

$treeLines.Add('')
$treeLines.Add('- Root files')

foreach ($file in $rootFiles) {
    $filePath = Join-Path $projectRoot $file

    if (Test-Path -LiteralPath $filePath) {
        $treeLines.Add("  - $file")
    }
}

$startMarker = '<!-- GENERATED_PROJECT_STRUCTURE_START -->'
$endMarker = '<!-- GENERATED_PROJECT_STRUCTURE_END -->'

$blockLines = @(
    $startMarker
    '## Generated Project Structure'
    ''
    '> Automatically generated by `scripts/generate-project-structure.ps1`. Do not edit this section manually.'
    ''
)

$blockLines += $treeLines

$blockLines += @(
    ''
    $endMarker
)

$generatedBlock = $blockLines -join "`r`n"

if (-not (Test-Path -LiteralPath $outputPath)) {
    New-Item `
        -ItemType Directory `
        -Path (Split-Path -Parent $outputPath) `
        -Force | Out-Null

    Set-Content `
        -LiteralPath $outputPath `
        -Value "# Project Structure`r`n" `
        -Encoding utf8
}

$content = Get-Content `
    -LiteralPath $outputPath `
    -Raw

$startIndex = $content.IndexOf($startMarker)
$endIndex = $content.IndexOf($endMarker)

if (
    $startIndex -ge 0 -and
    $endIndex -gt $startIndex
) {
    $afterEndIndex = $endIndex + $endMarker.Length

    $before = $content.Substring(0, $startIndex).TrimEnd()
    $after = $content.Substring($afterEndIndex).TrimStart()

    $newContent = "$before`r`n`r`n$generatedBlock"

    if ($after.Length -gt 0) {
        $newContent += "`r`n`r`n$after"
    }

    $newContent += "`r`n"
}
else {
    $newContent =
        $content.TrimEnd() +
        "`r`n`r`n" +
        $generatedBlock +
        "`r`n"
}

Set-Content `
    -LiteralPath $outputPath `
    -Value $newContent `
    -Encoding utf8

Write-Host ''
Write-Host 'Project structure updated:'
Write-Host $outputPath
Write-Host ''